"""Deterministic README, `.env.example` and CI workflow for the published repo. No LLM, no network."""

from poc_studio.schemas.architecture import Architecture
from poc_studio.schemas.deck import DeckPlan
from poc_studio.schemas.requirements import Requirements

CI_WORKFLOW = """\
name: ci

on:
  push:
    branches: [main]
  pull_request:

jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 24
          cache: npm
      - run: npm {install} --ignore-scripts
      - run: npm run build
"""

ENV_EXAMPLE = """\
# Copy this file to .env.local and fill in real values. Never commit .env.local.
# The prototype runs on mock data and needs no keys. Add keys here when you connect real services.
NEXT_PUBLIC_APP_NAME={name}
"""


def ci_workflow(has_lockfile: bool) -> str:
    return CI_WORKFLOW.format(install="ci" if has_lockfile else "install")


def env_example(title: str) -> str:
    return ENV_EXAMPLE.format(name=title.replace("\n", " ")[:80])


def build_readme(
    req: Requirements, arch: Architecture, plan: DeckPlan, *, docs: list[str], deck: list[str]
) -> str:
    """`docs` and `deck` are repo-relative file paths that exist in the publish folder."""
    out = [f"# {req.title}", "", f"Proof of concept for {req.client}, generated by PoC Studio.", ""]
    out += ["## Problem", "", req.summary, ""]
    out += [f"- {p}" for p in req.pain_points]
    out += ["", "## Features", ""]
    out += [f"- **{f.name}** ({f.priority}): {f.detail}" for f in req.features]
    out += ["", "## Architecture", "", arch.rationale, "", "```mermaid", arch.mermaid.strip(), "```", ""]
    out += ["### Components", ""] + [f"- **{c.name}** ({c.kind}): {c.detail}" for c in arch.components]
    out += ["", "### Models", "", "| Job | Model | Cost per 1k calls |", "| --- | --- | --- |"]
    out += [f"| {m.job} | {m.model} | ${m.cost_per_1k_calls_usd:,.2f} |" for m in arch.models]
    cost = arch.monthly_cost
    out += ["", "### Monthly cost", "", "| Item | USD |", "| --- | --- |"]
    out += [f"| {line.item} | ${line.usd:,.2f} |" for line in cost.lines]
    out += [f"| **Total** | **${cost.total_usd:,.2f}** |", "", f"Assumptions: {cost.assumptions}", ""]
    out += ["## Run locally", "", "```bash", "npm install", "npm run dev", "```", ""]
    out += ["Open http://127.0.0.1:3000. The prototype uses mock data.", ""]
    links = [f"- [{p}]({p})" for p in docs + deck]
    if links:
        out += ["## Documents", ""] + links + [""]
    out += [f"_{plan.data_note}. Generated by PoC Studio._", ""]
    return "\n".join(out)
